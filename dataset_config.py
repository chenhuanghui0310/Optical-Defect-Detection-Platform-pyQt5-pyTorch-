# -*- coding: utf-8 -*-
"""
数据集配置管理模块
用于自定义数据生成参数
"""

import json
from pathlib import Path
from dataclasses import dataclass, asdict
from typing import Dict, List, Tuple


@dataclass
class DefectConfig:
    """缺陷类型配置"""
    name: str                          # 缺陷名称
    enabled: bool = True               # 是否生成此类型
    samples_ratio: float = 0.25        # 占总样本的比例

    # 划痕参数范围
    scratch_length_range: Tuple = (50, 200)
    scratch_angle_range: Tuple = (0, 360)
    scratch_count_range: Tuple = (1, 4)

    # 突起/凹陷参数范围
    bump_count_range: Tuple = (1, 5)
    bump_height_range: Tuple = (0.1, 0.5)

    # 灰尘参数范围
    dust_count_range: Tuple = (1, 8)
    dust_size_range: Tuple = (10, 50)


@dataclass
class OpticalConfig:
    """光学参数配置"""
    wavelength_range: Tuple = (630, 700)          # 波长 nm
    oblique_angle_range: Tuple = (0.1, 5.0)       # 倾斜角 °
    simulation_size_base: int = 512               # 仿真网格基础大小
    dpi: int = 100                                # 导出DPI


class DatasetConfig:
    """数据集配置管理"""

