import argparse
import json
import shutil
from pathlib import Path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Export bump/dent error samples from validate_small_targets JSON output."
    )
    parser.add_argument(
        "--report",
        type=str,
        required=True,
        help="Path to JSON report generated by validate_small_targets.py",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default=str(Path(__file__).resolve().parent / "runs" / "error_exports" / "small_targets"),
        help="Directory to store exported error samples",
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Remove existing exported cases in output-dir before exporting new ones",
    )
    return parser.parse_args()


def _safe_name(image_path: Path) -> str:
    return image_path.stem.replace(" ", "_")


def _write_summary(target_dir: Path, item: dict) -> None:
    summary = {
        "image": item.get("image", ""),
        "expected": item.get("expected", ""),
        "error_type": item.get("error_type", ""),
        "best_same_class_iou": item.get("best_same_class_iou", 0.0),
        "expected_count": item.get("expected_count", 0),
        "predicted_count": item.get("predicted_count", 0),
        "predicted_labels": item.get("predicted_labels", []),
        "predictions": item.get("predictions", []),
    }
    (target_dir / "summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def _copy_if_exists(src: Path | None, dst: Path) -> None:
    if src and src.exists():
        shutil.copy2(src, dst)


def _review_priority(item: dict) -> int:
    expected = str(item.get("expected", "")).strip().lower()
    error_type = str(item.get("error_type", "")).strip().lower()
    labels = {str(label).strip().lower() for label in item.get("predicted_labels", [])}
    if expected == "dent" and error_type == "confused_small_target" and "bump" in labels:
        return 0
    if expected == "bump" and error_type == "missed_all":
        return 1
    if expected == "bump" and error_type == "confused_small_target" and "dent" in labels:
        return 2
    if expected == "dent" and error_type == "missed_all":
        return 3
    if error_type == "localized_poorly":
        return 4
    return 5


def _write_review_queue(output_dir: Path, exported_items: list[dict]) -> None:
    queue = []
    for item in exported_items:
        image_path = Path(item["image"])
        expected = str(item.get("expected", "")).strip().lower()
        case_dir = output_dir / expected / item["case_name"]
        queue.append(
            {
                "priority": _review_priority(item),
                "expected": expected,
                "error_type": item.get("error_type", ""),
                "image_name": image_path.name,
                "image": item["image"],
                "case_dir": str(case_dir),
                "summary_json": str(case_dir / "summary.json"),
                "predicted_labels": item.get("predicted_labels", []),
                "best_same_class_iou": item.get("best_same_class_iou", 0.0),
                "expected_count": item.get("expected_count", 0),
                "predicted_count": item.get("predicted_count", 0),
            }
        )
    queue.sort(
        key=lambda row: (
            row["priority"],
            row["expected"],
            row["error_type"],
            row["best_same_class_iou"],
            row["image_name"],
        )
    )
    (output_dir / "review_queue.json").write_text(
        json.dumps(queue, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


def _read_json_report(report_path: Path) -> dict:
    raw = report_path.read_bytes()
    for encoding in ("utf-8", "utf-8-sig", "utf-16", "utf-16-le", "utf-16-be", "gb18030"):
        try:
            return json.loads(raw.decode(encoding))
        except Exception:
            continue
    raise ValueError(f"Cannot decode JSON report with supported encodings: {report_path}")


def export_errors(report_path: Path, output_dir: Path) -> tuple[int, int]:
    report = _read_json_report(report_path)
    errors = report.get("errors", [])
    if not isinstance(errors, list):
        raise ValueError("Invalid report format: errors must be a list")

    bump_count = 0
    dent_count = 0
    output_dir.mkdir(parents=True, exist_ok=True)
    exported_items: list[dict] = []

    for index, item in enumerate(errors, start=1):
        image_raw = item.get("image")
        expected = str(item.get("expected", "")).strip().lower()
        if not image_raw or expected not in {"bump", "dent"}:
            continue

        image_path = Path(image_raw)
        label_path = image_path.parents[2] / "labels" / image_path.parent.name / f"{image_path.stem}.txt"
        target_root = output_dir / expected
        target_root.mkdir(parents=True, exist_ok=True)
        case_name = f"{index:03d}_{_safe_name(image_path)}"
        case_dir = target_root / case_name
        case_dir.mkdir(parents=True, exist_ok=True)

        _copy_if_exists(image_path, case_dir / image_path.name)
        _copy_if_exists(label_path, case_dir / f"{image_path.stem}.txt")
        _write_summary(case_dir, item)
        exported_items.append(
            {
                **item,
                "case_name": case_name,
            }
        )

        if expected == "bump":
            bump_count += 1
        else:
            dent_count += 1

    _write_review_queue(output_dir, exported_items)
    return bump_count, dent_count


def main() -> None:
    args = parse_args()
    report_path = Path(args.report).expanduser().resolve()
    output_dir = Path(args.output_dir).expanduser().resolve()

    if not report_path.exists():
        raise FileNotFoundError(f"Report not found: {report_path}")
    if args.clean and output_dir.exists():
        shutil.rmtree(output_dir)

    bump_count, dent_count = export_errors(report_path, output_dir)
    print(f"Exported bump errors: {bump_count}")
    print(f"Exported dent errors: {dent_count}")
    print(f"Output dir: {output_dir}")
    print(f"Review queue: {output_dir / 'review_queue.json'}")


if __name__ == "__main__":
    main()
